-- 1. 任务表（id 自增、priority 存中文）
create table if not exists public.tasks (
  id         bigint generated by default as identity primary key,
  title      text        not null,
  priority   text        not null check (priority in ('高', '中', '低')),
  completed  boolean     not null default false,
  created_at timestamptz not null default now()
);

-- 2. 按创建时间倒序查询的索引
create index if not exists tasks_created_at_desc_idx on public.tasks (created_at desc);

-- 3. 行级安全（RLS）
alter table public.tasks enable row level security;

-- 演示用：允许匿名读写（生产环境请改为按 auth.uid() 隔离，见 README）
drop policy if exists "tasks anon all" on public.tasks;
create policy "tasks anon all"
  on public.tasks
  for all
  to anon, authenticated
  using (true)
  with check (true);
